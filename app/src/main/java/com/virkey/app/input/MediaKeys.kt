package com.virkey.app.input

/** Consumer Page (0x0C), USB HID Usage Tables 1.6, sections 15.7 and 15.9. */
object MediaKeys {
    const val MUTE = 0xE2
    const val VOLUME_DOWN = 0xEA
    const val VOLUME_UP = 0xE9
    const val PREVIOUS = 0xB6
    const val PLAY_PAUSE = 0xCD
    const val NEXT = 0xB5
    const val STOP = 0xB7
}
